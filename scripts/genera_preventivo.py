H1_ORPHAN = (A4[1] - 2.2 * cm - 2.0 * cm) * 0.15


def h1(text):
    return [CondPageBreak(H1_ORPHAN),
            Paragraph(f"<b>{text}</b>", st_h1),
            HRFlowable(width="100%", color=BORDER, thickness=0.8, spaceBefore=0, spaceAfter=8)]


def table_std(data_rows, header, ratios, caption=None, align_map=None):
    """Tabella standard: celle Paragraph, header HEADER_FILL, righe alternate."""
    col_w = [r * AVAIL_W for r in ratios]
    assert abs(sum(col_w) - AVAIL_W) < 1.0
    rows = [[Paragraph(f"<b>{h}</b>", st_th) for h in header]]
    for r in data_rows:
        cells = []
        for i, c in enumerate(r):
            style = st_td_c if (align_map and align_map[i] == "c") else st_td
            if align_map and align_map[i] == "b":
                cells.append(Paragraph(f"<b>{c}</b>", st_td))
            else:
                cells.append(Paragraph(str(c), style))
        rows.append(cells)
    t = Table(rows, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    style_cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for i in range(1, len(rows)):
        style_cmds.append(("BACKGROUND", (0, i), (-1, i),
                           TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style_cmds))
    out = [Spacer(1, 8), t]
    if caption:
        out += [Spacer(1, 4), Paragraph(caption, st_caption)]
    out.append(Spacer(1, 6))
    return out


